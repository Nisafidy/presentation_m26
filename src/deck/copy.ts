export function loadDeck(): { copy: Copy; notes: string[] } {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return { copy: { ...defaultCopy }, notes: [...defaultNotes] };
    const parsed = JSON.parse(raw) as { copy?: Partial<Copy>; notes?: string[] };
    return {
      copy: { ...defaultCopy, ...(parsed.copy ?? {}) },
      notes: defaultNotes.map((note, i) => parsed.notes?.[i] || note),
    };
  } catch {
    return { copy: { ...defaultCopy }, notes: [...defaultNotes] };
  }
}
